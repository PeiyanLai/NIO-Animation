import React from 'react';

/**
 * 蔚来 Logo —— 上「天空」拱门 + 下「道路」人字。
 *
 * ## 别凭印象画
 *
 * 这个标最容易画错成「一条半圆弧 + 一个梯形」。真实几何是两个**实心块**：
 *   上：一个**拱门**（外弧贴外接圆，中间挖掉一个小半圆，平底）——Sky
 *   下：一个**人字带**（平顶 + Λ 形底缘，中间薄、两端厚）——Action
 * 两块之间有一条很细的横向缝，缝的位置**高于圆心**。
 *
 * ## 比例怎么来的
 *
 * 取实拍轮毂中心盖（`photos/es9/es9-wheel-dabing.jpg`）→ 以盘心归一化重采样 →
 * 二值化 → 对「内弧半径 / 平底高度 / 缝宽 / Λ 顶点 / Λ 端点」五个参数做网格搜索，
 * 取 IoU 最大。**实测 IoU 0.871**，改写成 SVG 路径后复测 0.866（差值来自抗锯齿）。
 * 残差集中在照片本身的高光和轻微倾斜上，不是形状误差。
 *
 * 归一化比例（外接圆半径 R = 1）：
 *   拱门：内弧 r = 0.467R，与外弧共圆心 (0, -0.178R)，平底 y = -0.178R
 *   人字：顶边 y = -0.155R；底缘 Λ 顶点 (0, 0.222R)，两端 (±0.7066R, 0.7077R) 落在外接圆上
 *
 * ## 为什么不用 clipPath
 *
 * 两个形状的端点**直接算在外接圆上**，路径自己就闭合在圆周，不需要裁剪。
 * 这样同一个 SVG 里画多个轮子时不会有重复 id 的问题（车轮通常前后各一个）。
 */
export const NioLogo: React.FC<{
  /** 外接圆半径（logo 的整体大小） */
  r?: number;
  fill?: string;
  opacity?: number;
}> = ({r = 1, fill = '#FFFFFF', opacity = 1}) => {
  const f = (v: number) => (v * r).toFixed(3);

  // 拱门：外弧沿外接圆从左端翻到右端（159.5°，不到半圈 → large-arc=0, sweep=1），
  // 收到内弧右端，内弧反向翻回左端（sweep=0），闭合成平底的拱。
  const arch =
    `M${f(-0.984)} ${f(-0.178)}` +
    `A${f(1)} ${f(1)} 0 0 1 ${f(0.984)} ${f(-0.178)}` +
    `L${f(0.467)} ${f(-0.178)}` +
    `A${f(0.467)} ${f(0.467)} 0 0 0 ${f(-0.467)} ${f(-0.178)}Z`;

  // 人字：平顶两端落在外接圆上，两侧沿圆弧下行到 Λ 端点，再折回顶点。
  const chevron =
    `M${f(-0.988)} ${f(-0.155)}L${f(0.988)} ${f(-0.155)}` +
    `A${f(1)} ${f(1)} 0 0 1 ${f(0.7066)} ${f(0.7077)}` +
    `L0 ${f(0.222)}` +
    `L${f(-0.7066)} ${f(0.7077)}` +
    `A${f(1)} ${f(1)} 0 0 1 ${f(-0.988)} ${f(-0.155)}Z`;

  return (
    <g fill={fill} opacity={opacity}>
      <path d={arch} />
      <path d={chevron} />
    </g>
  );
};
