#!/usr/bin/env node
/**
 * 把动画决策卡（*-manifest.json）转成实拍分镜表（shot list）。
 *
 *   node make-shotlist.mjs ramp-manifest.json > ramp-shotlist.md
 *
 * 为什么这一步值钱：决策卡里已经有了拍摄最缺的三样东西 ——
 *   chapters[].claim            → 每个镜头要证明什么（导演要的「这条为什么存在」）
 *   acceptance[] 里的数字        → 镜头必须拍到的可量化事实（验收时拿它对素材）
 *   conceptualItems[]           → **必须先变成真实存在的样件，否则这个镜头拍不了**
 *
 * 最后一条是实拍与插画的分水岭：概念件可以画，但拍不出来。
 */
import {readFileSync} from 'node:fs';

const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith('--'));
const audArg = (args.find((a) => a.startsWith('--audience=')) || '').split('=')[1];
if (!file) {
  console.error('用法: node make-shotlist.mjs <manifest.json> [--audience=internal|external]');
  process.exit(2);
}
const m = JSON.parse(readFileSync(file, 'utf8'));
/** 受众决定合规强度与样件门槛：对内宣讲宽得多，但不是零 */
const AUD = audArg || m.audience || 'external';
const INTERNAL = AUD === 'internal';

/** scope → 默认景别 / 机位建议（可在分镜表里手改，这里只给起点） */
const FRAMING = {
  'vehicle-exterior': {
    shots: ['全景（车身完整入画，低机位 ~0.9m）', '中景（功能部位，机位与部位等高）', '特写（机械动作，30–50cm）'],
    note: '低机位显车身姿态；功能部位机位要与部位等高，俯拍会丢失高度差信息',
  },
  cockpit: {
    shots: ['过肩（从后排越过前排肩线）', '中景（中控与岛台全貌）', '特写（手部操作与反馈）'],
    note: '车内光比大，需补光；屏幕要单独拍一条无摩尔纹的版本供后期贴屏',
  },
  'vehicle-environment': {
    shots: ['跟车（并行伴随）', '车内 POV（看向路面）', '车机屏特写（提醒弹出）'],
    note: '路面材质要在画面里可辨（雪/泥/沙），否则「识别地形」这件事看不出来',
  },
  'vehicle-ecosystem': {
    shots: ['中景（人 + 设备 + 车的关系）', '特写（设备本体与接口）', '结果镜（可感知的变化）'],
    note: '外设必须有可用样件；接口咬合这类动作要拍慢动作（120fps）留给后期',
  },
  'vehicle-system': {
    shots: ['实拍空镜（车辆静态）', '后期叠加层（不可见系统示意）'],
    note: '不可见系统只能靠后期动态图形，实拍部分只负责提供承载画面',
  },
  'fleet-topology': {
    shots: ['航拍（车队队形全貌）', '跟车（单车视角）', '车机屏特写（组队状态）'],
    note: '航拍需空域许可；队形与车距要按脚本实测标记地面点位',
  },
};

const num = /[0-9]/;
const numeric = (m.acceptance || []).filter((a) => num.test(a));
const nonNumeric = (m.acceptance || []).filter((a) => !num.test(a));
const f = FRAMING[m.scope] || {shots: ['全景', '中景', '特写'], note: ''};
const L = [];
const P = (s = '') => L.push(s);

P(`# ${m.title} · 实拍分镜表`);
P();
P(`> 由 \`${file}\` 自动生成。**这是拍摄前的技术底稿，不是最终分镜**——`);
P('> 景别与机位只给了起点，需要导演/摄影指导按场地和车辆实况改。');
P();
P(`- 演示空间：\`${m.scope}\`　机制：${(m.mechanism || []).join(' / ')}`);
P(`- 车辆：${m.vehicle || '待定'}`);
P(`- **受众：${INTERNAL ? '对内宣讲' : '对外传播'}**${INTERNAL
  ? '　→ 不追求电影质感；目的是让人看懂机构与边界，样件可用工程件/平替，但必须在片中标注'
  : '　→ 对外口径，合规从严；概念件不得出镜'}`);
P();

P('## 一、开拍前必须归零的项');
P();
if ((m.conceptualItems || []).length === 0) {
  P('决策卡里没有未定义项 —— 具备开拍条件。');
} else if (INTERNAL) {
  P(`决策卡里还有 **${m.conceptualItems.length} 项未定义**。对内宣讲**不要求它们全部归零**——`);
  P('可以用 3D 打印件、纸板样件、甚至**市售平替**先拍，只要在片中明确标注');
  P('「工程样件 / 市售平替，非最终设计」。');
  P();
  P('**反过来说，这正是对内实拍最大的价值**：动画只能证明几何成立，');
  P('实拍能回答动画永远回答不了的问题 —— 狗到底肯不肯走上去、猫在包里闹不闹、');
  P('手伸过去顺不顺。买个市售平替花一下午就能验，比讨论三轮有用。');
  P();
  P('| # | 未定义项 | 归零方式 |');
  P('|---|---|---|');
  const KIND = INTERNAL ? [
    [/外观|形态|材质|造型|开口|折叠|收纳/, '3D 打印 / 纸板 / 市售平替均可，需标注'],
    [/尺寸|长度|高度|绳长|坡度|距离|承重|体型|区间|上限/, '现场实测并记录，片中标为实测值'],
    [/按键|键位|接口|固定|锁|铰接/, '可用临时机构演示动作，需标注非最终形式'],
    [/UI|界面|卡片|提示|回显/, '用设计稿贴屏或后期叠加，需标注概念 UI'],
    [/概念示意|概念平面|非实拍/, '改为实拍，本项自然消失'],
  ] : [
    [/外观|形态|材质|造型|开口|折叠|收纳/, '出可出镜样件'],
    [/尺寸|长度|高度|绳长|坡度|距离|承重|体型|区间|上限/, '冻结参数并实测'],
    [/按键|键位|接口|固定|锁|铰接/, '出可操作样件 + 冻结交互'],
    [/UI|界面|卡片|提示|回显/, '出可上车的正式 UI'],
    [/概念示意|概念平面|非实拍/, '改为实拍，本项自然消失'],
  ];
  m.conceptualItems.forEach((c, i) => {
    const k = KIND.find(([re]) => re.test(c));
    P(`| ${i + 1} | ${c} | **${k ? k[1] : '需产品确认后冻结'}** |`);
  });
}
P();

P('## 二、逐章镜头');
P();
for (const [i, c] of (m.chapters || []).entries()) {
  P(`### 第 ${i + 1} 章 · ${c.claim}`);
  P();
  P(`- **这一章要证明**：${c.claim}`);
  P(`- **起幅**：${c.startState}`);
  P(`- **落幅**：${c.endState}`);
  P(`- **场景**：${c.scene}`);
  P();
  P('| 镜号 | 景别 / 机位 | 内容 | 时长 |');
  P('|---|---|---|---|');
  f.shots.forEach((s, k) => {
    P(`| ${i + 1}-${k + 1} | ${s} | ${k === 0 ? '交代关系' : k === 1 ? c.claim : '动作 / 结果的可感知细节'} | ${k === 2 ? '2–3s' : '3–4s'} |`);
  });
  P();
}

P('## 三、必须拍到的可量化事实（验收用）');
P();
P('拍回来的素材要能证明这些，否则这条 claim 在片子里是空的：');
P();
numeric.length
  ? numeric.forEach((a) => P(`- [ ] ${a}`))
  : P('- （决策卡的验收条件里没有可量化项，建议补齐后再开拍）');
P();
if (nonNumeric.length) {
  P('其余验收条件（表现层，后期把关）：');
  nonNumeric.forEach((a) => P(`- [ ] ${a}`));
  P();
}

P('## 四、拍摄注记');
P();
if (f.note) P(`- ${f.note}`);
if (INTERNAL) {
  P('- **器材够用就行**：手机 4K + 三脚架 + 一盏补光灯。对内宣讲要的是「看得清机构」，不是氛围');
  P('- **优先拍动画拍不出来的东西**：真实的犹豫、真实的失败、真实的耗时。');
  P('  「狗第一次不肯上、第三次才走」这种镜头对内部决策的价值远高于一条完美的演示');
}
P('- 机械动作（开合 / 咬合 / 锁止）拍 120fps 慢动作版本，后期可放慢强调');
P('- 每个动作拍「一次完整 + 一次分解」两条，剪辑时可切');
P('- 同一动作的**起幅与落幅各留 1s 静止**，方便与后期叠加层对齐');
P();

if (INTERNAL) {
  P('## 五、合规（对内宣讲：宽得多，但不是零）');
  P();
  P('**仍然要做的**：');
  P('- **知悉范围**：未上市功能即使对内也有知悉范围，确认这次宣讲的听众都在范围内');
  P('- **工程车 / 样件保密**：出镜前确认可拍摄范围，素材归档到内部空间，不进个人网盘/微信群');
  P('- **参与者知情同意**：同事出镜口头确认即可，但要说明用途与留存范围');
  P('- **片头标识**：「内部资料 · 请勿外传」+「工程样件，非最终设计」——内部素材外流是常态，标识是最后一道防线');
  P('- **动物**：主人全程在场，不强迫、不诱导做超出能力的动作，随时可中止');
  P('- **口径**：概念值必须标为「概念推算」，不要在片中当成实车规格念出来');
  P();
  P('**可以免掉的**（这些是对外传播才需要的）：对外披露审批 · 肖像权公开使用授权 ·');
  P('广告法合规审查 · 商业场地与空域许可 · 外观伪装。');
} else {
  P('## 五、合规（对外传播：实拍比插画严，必须提前走流程）');
  P();
  P('- **未上市功能对外披露**：需要产品与法务书面确认可披露范围与口径');
  P('- **工程车 / 试装车出镜**：保密与外观伪装要求，谁批准、拍完素材归谁');
  P('- **出镜人员**：肖像权授权书，含使用范围与期限');
  P('- **动物出镜**：驯导师在场、动物福利与工时限制、拍摄前兽医确认、现场应急预案');
  P('- **场地与航拍**：场地许可、空域许可、保险');
  P('- **口径一致性**：片中出现的每个数字都要与决策卡一致；决策卡里标为概念值的数字**不得**出现在实拍片中');
}
P();

process.stdout.write(L.join('\n') + '\n');
